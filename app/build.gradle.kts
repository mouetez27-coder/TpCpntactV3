import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
}

// La clé Google Maps n'est jamais versionnée : elle est lue depuis local.properties
// (fichier ignoré par Git) et injectée dans le manifest via un placeholder.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) {
        file.inputStream().use { load(it) }
    }
}
val mapsApiKey: String = localProperties.getProperty("MAPS_API_KEY").orEmpty()

android {
    namespace = "com.example.tpcontacts"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.example.tpcontacts"
        minSdk = 24
        targetSdk = 37
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        manifestPlaceholders["MAPS_API_KEY"] = mapsApiKey
    }

    buildTypes {
        release {
            optimization {
                enable = false
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
}

